let currentLanguage = normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));

export function normalizeLanguage(language) {
  if (LANGUAGE_VALUES.has(language)) return language;
  return "en";
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  currentLanguage = normalizeLanguage(language);
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
  const meta = META[currentLanguage] || META.en;
  document.documentElement.lang = currentLanguage === "zh" ? "zh-Hans" : currentLanguage;
  document.documentElement.dir = meta.dir;
  document.title = t("documentTitle");
  return currentLanguage;
}

export function languageMeta() {
  return META[currentLanguage] || META.en;
}

export function t(key, params = {}) {
  const template = TRANSLATIONS[currentLanguage]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

export function applyDocumentTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
}

export function number(value) {
  return new Intl.NumberFormat(languageMeta().locale).format(value);
}

export function views(count) {
  if (!count && count !== 0) return "";
  return t("views", { count: number(count) });
}

export function itemCount(count) {
  return t("items", { count: number(count || 0) });
}

