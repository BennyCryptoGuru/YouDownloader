export function eta(seconds) {
  if (!seconds && seconds !== 0) return "";
  const value = Number(seconds);
  const hours = Math.floor(value / 3600);
  const minutes = Math.floor((value % 3600) / 60);
  const secs = Math.floor(value % 60);
  if (hours > 0) return `${hours} ${t("unitHourShort")} ${String(minutes).padStart(2, "0")} ${t("unitMinuteShort")}`;
  if (minutes > 0) return `${minutes} ${t("unitMinuteShort")} ${String(secs).padStart(2, "0")} ${t("unitSecondShort")}`;
  return `${secs} ${t("unitSecondShort")}`;
}
